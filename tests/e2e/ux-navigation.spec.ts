import { filterByGameDate } from './helpers/game-filters'
import { test, expect, continueRegistration, discardRegistration, registerGameSelection, openRegistration, fillOrganizer, fillPlayer, playerField, activatePlayer, noNewBookings } from './helpers/checkout-harness'

test.describe('Approved guided registration navigation', () => {
  test('UX-WIZ-01 mobile steps retain per-game drafts and reveal the first invalid collapsed player', async ({ owned, scenario, page }, info) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/club'); await filterByGameDate(page, scenario.date)
    const games = scenario.games.slice(0, 2)
    for (const game of games) await page.getByRole('article').filter({ has: page.getByRole('heading', { name: game.venue, exact: true }) }).getByRole('button', { name: /^Select / }).click()
    await page.getByRole('region', { name: 'Game selection' }).getByRole('button', { name: 'Continue to registration', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog.getByRole('heading', { name: 'Game 1 of 2 · Your player details', exact: true })).toBeVisible()
    // Visibility can precede the end of the dialog entrance animation.
    await expect.poll(() => dialog.boundingBox()).toEqual({
      x: 0, y: 0, width: 390, height: 844,
    })
    await expect(dialog.getByRole('region', { name: /^Registration for / })).toHaveCount(1)
    await fillOrganizer(page, 'QA Guided Organizer')
    await fillPlayer(playerField(page))
    await continueRegistration(page, 'Add another player')
    await playerField(page, 2).getByRole('checkbox', { name: 'Player details available', exact: true }).check()
    await playerField(page, 2).getByLabel(/^Name/).fill('QA Guided Teammate')
    await fillPlayer(playerField(page, 2))
    await playerField(page, 2).getByLabel(/^Birthday/).fill('')
    await activatePlayer(page)
    await expect(dialog.locator('.club-checkout-player')).toHaveCount(1)
    await continueRegistration(page, 'Next game')
    await expect(playerField(page, 2).getByLabel(/^Birthday/)).toBeFocused()
    await expect(dialog.getByRole('heading', { name: 'Game 1 of 2 · Players', exact: true })).toBeVisible()
    await playerField(page, 2).getByLabel(/^Birthday/).fill('1998-08-14')
    await continueRegistration(page, 'Next game')
    await expect(dialog.getByRole('heading', { name: 'Game 2 of 2 · Your player details', exact: true })).toBeFocused()
    await expect(dialog.getByRole('region', { name: /^Registration for / })).toHaveCount(1)
    await expect(dialog).toContainText(games[1].venue)
    await fillPlayer(playerField(page))
    await continueRegistration(page, 'Add another player')
    await dialog.getByRole('button', { name: 'Back', exact: true }).click()
    await expect(dialog).toContainText(games[0].venue)
    await expect(dialog).toContainText('2 players · Group registration')
    await expect(playerField(page, 2).getByLabel(/^Name/)).toHaveValue('QA Guided Teammate')
    await expect(playerField(page, 2).getByLabel(/^Birthday/)).toHaveValue('1998-08-14')
    await activatePlayer(page)
    await expect(playerField(page).getByLabel(/^Birthday/)).toHaveValue('1995-04-12')
    await continueRegistration(page, 'Next game')
    await expect(dialog).toContainText('2 players · Group registration')
    await expect(dialog.locator('.club-checkout-player')).toHaveCount(1)
    const next = dialog.getByRole('button', { name: 'Continue to contact', exact: true })
    await next.scrollIntoViewIfNeeded(); await expect(next).toBeInViewport()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('guided-mobile-game-two.png'), fullPage: true })
    const reviewed = page.waitForResponse(response => response.url().endsWith('/api/club') && response.request().postDataJSON()?.action === 'checkout.review')
    await continueRegistration(page, 'Review registration')
    const response = await reviewed; expect(response.status()).toBe(200)
    const payload = response.request().postDataJSON().data
    expect(payload.games).toHaveLength(2)
    expect(payload.games[0].players[1]).toMatchObject({ name: 'QA Guided Teammate', birth_date: '1998-08-14' })
    expect(payload.games[1].players).toHaveLength(2)
    await expect(dialog.getByRole('heading', { name: 'Review your registration', exact: true })).toBeVisible()
    await noNewBookings(owned, scenario.baselineBookingId)
    await discardRegistration(page)
    await expect(page.getByRole('region', { name: 'Game selection' }).getByRole('button', { name: 'Continue to registration', exact: true })).toBeFocused()
  })

  test('UX-WIZ-02 dirty Close and Escape keep drafts until explicit discard without creating holds', async ({ owned, scenario, page }, info) => {
    await openRegistration(page, owned)
    await fillOrganizer(page, 'QA Preserved Organizer')
    const dialog = page.getByRole('dialog')
    await fillPlayer(playerField(page), '1997-03-19')
    const birthday = playerField(page).getByLabel(/^Birthday/)
    await birthday.focus()
    await dialog.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(dialog.getByRole('heading', { name: 'Discard registration?', exact: true })).toBeVisible()
    await expect(dialog.getByRole('button', { name: 'Keep editing', exact: true })).toBeFocused()
    await expect(dialog.getByRole('heading', { name: 'Game 1 of 1 · Your player details', exact: true })).not.toBeVisible()
    await dialog.getByRole('button', { name: 'Keep editing', exact: true }).click()
    await expect(dialog.getByRole('heading', { name: 'Game 1 of 1 · Your player details', exact: true })).toBeVisible()
    await expect(birthday).toHaveValue('1997-03-19')
    await dialog.getByRole('button', { name: 'Next', exact: true }).click()
    await dialog.getByRole('button', { name: 'Back', exact: true }).click()
    await expect(playerField(page).getByLabel(/^Name/)).toHaveValue('QA Preserved Organizer')
    await birthday.focus(); await page.keyboard.press('Escape')
    await expect(dialog.getByRole('heading', { name: 'Discard registration?', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(dialog.getByRole('heading', { name: 'Game 1 of 1 · Your player details', exact: true })).toBeVisible()
    await expect(birthday).toBeFocused(); await expect(birthday).toHaveValue('1997-03-19')
    await page.screenshot({ path: info.outputPath('dirty-registration-keep-editing.png'), fullPage: true })
    await discardRegistration(page)
    await noNewBookings(owned, scenario.baselineBookingId)
    await registerGameSelection(page, page.getByRole('article').filter({ has: page.getByRole('heading', { name: owned.venueName, exact: true }) }))
    await expect(playerField(page).getByLabel(/^Name/)).toHaveValue('')
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
  })

  test('UX-WIZ-03 summaries and linked field errors stay truthful while an overallocated swap remains correctable', async ({ owned, scenario, page }, info) => {
    // Exactly one reservable Open and one Middle: the seeded legacy Open uses
    // the other persisted Open capacity. A temporary Open→Middle swap can be
    // corrected in the draft; no extra slot is granted by an editable option.
    await owned.patchPosition(owned.gameId, 'open', { capacity: 2 })
    await owned.patchPosition(owned.gameId, 'middle', { capacity: 1 })
    await owned.patchPosition(owned.gameId, 'opposite', { capacity: 0 })
    await owned.patchPosition(owned.gameId, 'setter', { capacity: 0 })
    await openRegistration(page, owned)
    await fillOrganizer(page)
    const dialog = page.getByRole('dialog'), first = dialog.locator('.club-checkout-person').first()
    await playerField(page).getByRole('checkbox', { name: 'Player details available', exact: true }).uncheck()
    await expect(first.locator('summary')).toContainText('Position only')
    await playerField(page).getByRole('checkbox', { name: 'Player details available', exact: true }).check()
    await expect(first.locator('summary')).toContainText('Details incomplete')
    await dialog.getByRole('button', { name: 'Next', exact: true }).click()
    const level = playerField(page).getByLabel(/^Skill level/)
    await expect(level).toBeFocused(); await expect(level).toHaveAttribute('aria-invalid', 'true')
    const describedBy = (await level.getAttribute('aria-describedby') || '').split(/\s+/)
    const errorId = describedBy.find(value => value.endsWith('-error'))
    expect(errorId).toBeTruthy()
    const fieldError = dialog.locator(`[id="${errorId}"]`)
    await expect(fieldError).toBeVisible(); await expect(fieldError).toContainText(/level/i)
    await level.blur()
    await expect(fieldError).toBeVisible()
    await fillPlayer(playerField(page))
    await expect(level).not.toHaveAttribute('aria-invalid', 'true')
    await expect(first.locator('summary')).toContainText('Details complete')
    await continueRegistration(page, 'Add another player')
    await expect(playerField(page, 2).getByLabel(/^Position/)).toHaveValue('middle')
    await activatePlayer(page)
    await playerField(page).getByLabel(/^Position/).selectOption('middle')
    await expect(dialog.getByRole('button', { name: 'Continue to contact', exact: true })).toBeDisabled()
    await expect(dialog).toContainText(/capacity|available|over/i)
    await activatePlayer(page, 2)
    await playerField(page, 2).getByLabel(/^Position/).selectOption('open')
    await expect(dialog.getByRole('button', { name: 'Continue to contact', exact: true })).toBeEnabled()
    await expect(playerField(page, 2).getByRole('checkbox', { name: 'Player details available', exact: true })).not.toBeChecked()
    await activatePlayer(page)
    await expect(playerField(page).getByLabel(/^Birthday/)).toHaveValue('1995-04-12')
    await expect(first.locator('summary')).toContainText('Details complete')
    await page.screenshot({ path: info.outputPath('corrected-capacity-swap-and-details.png'), fullPage: true })
    await noNewBookings(owned, scenario.baselineBookingId)
  })

})
