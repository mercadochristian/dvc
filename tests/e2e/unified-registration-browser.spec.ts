      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: info.outputPath(`owner-edit-cutoff-error-${viewport.name}.png`), fullPage: true })
