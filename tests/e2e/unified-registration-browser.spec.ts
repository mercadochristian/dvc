  test('EDIT-UX-02 a committed edit with a withheld response times out safely and Escape refreshes the saved version', async ({ owned, scenario, context, page }, info) => {
    await owned.bootstrap(context)
    const { checkout } = await confirmedHold(owned, context, owned.draft([{ game_id: scenario.games[1].id, kind: 'group', organizer_plays: false, players: [owned.player('open', null, false), owned.player('setter', null, false)] }]))
    const booking = checkout.bookings[0]
    const rowsBefore = await owned.rows('roster_entries', { booking_id: `eq.${booking.id}`, order: 'id' })
    const target = rowsBefore.find(row => row.position === 'setter')!, sibling = rowsBefore.find(row => row.position === 'open')!
    const bookingBefore = await owned.rows('bookings', { id: `eq.${booking.id}` })
    const checkoutBefore = await owned.rows('checkouts', { id: `eq.${checkout.id}` })
    await page.goto('/club'); await page.getByRole('button', { name: 'My bookings', exact: true }).click()
    const card = page.getByRole('article').filter({ hasText: checkout.id })
    const opener = card.getByRole('button', { name: 'Edit player details', exact: true })
    await opener.click()
    const dialog = page.getByRole('dialog', { name: 'Edit player details', exact: true })
    await dialog.getByLabel('Choose player', { exact: true }).selectOption(String(target.id))
    const player = dialog.getByRole('group', { name: /^Player \d+ details$/ })
    await player.getByRole('checkbox', { name: 'Player details available', exact: true }).check()
    await player.getByLabel(/^Name/).fill('QA Confirmed After Refresh')
    await fillPlayer(player)
    let release!: () => void, committed = false, settled = false, updates = 0
    const gate = new Promise<void>(resolve => { release = resolve })
    await page.route('**/api/club', async route => {
      if (route.request().method() !== 'POST' || route.request().postDataJSON()?.action !== 'booking.player.update') { await route.continue(); return }
      updates++
      try {
        const actual = await route.fetch()
        expect(actual.status()).toBe(200)
        expect(await actual.json()).toMatchObject({ entry: { id: target.id, booking_id: booking.id, name: 'QA Confirmed After Refresh', version: Number(target.version) + 1 } })
        expect((await owned.rows('roster_entries', { id: `eq.${target.id}` }))[0]).toMatchObject({ name: 'QA Confirmed After Refresh', version: Number(target.version) + 1 })
        committed = true
        await gate // The real mutation has committed; only reply delivery waits.
        await route.abort('failed')
      } finally { settled = true }
    })
    try {
      const started = Date.now()
      await dialog.getByRole('button', { name: 'Save player details', exact: true }).click()
      await expect.poll(() => committed, { timeout: 10_000 }).toBe(true)
      await expect(dialog.getByRole('alert')).toContainText('The save result could not be confirmed', { timeout: 25_000 })
      expect(Date.now() - started).toBeGreaterThanOrEqual(20_000)
      await expect(dialog.getByRole('button', { name: 'Save player details', exact: true })).toBeDisabled()
      await expect(dialog.getByRole('button', { name: 'Close and refresh bookings', exact: true })).toBeEnabled()
      await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeEnabled()
      expect(updates).toBe(1)
      for (const viewport of [{ name: 'desktop', width: 1280, height: 900 }, { name: 'mobile', width: 390, height: 844 }]) {
        await page.setViewportSize({ width: viewport.width, height: viewport.height })
        await dialog.getByRole('alert').scrollIntoViewIfNeeded()
        await page.screenshot({ path: info.outputPath(`owner-edit-unknown-result-${viewport.name}.png`), fullPage: true })
      }
      const refreshed = page.waitForResponse(response => response.request().method() === 'GET' && new URL(response.url()).searchParams.get('view') === 'mine')
      await page.keyboard.press('Escape')
      await expect(dialog).toHaveCount(0)
      const mine = await refreshed
      expect(mine.status()).toBe(200)
      const recovered = (await mine.json()).find((row: { id: string }) => row.id === booking.id)
      expect(recovered.entries.find((row: { id: string }) => row.id === target.id)).toMatchObject({ name: 'QA Confirmed After Refresh', version: Number(target.version) + 1 })
      await expect(opener).toBeFocused()
      release(); await expect.poll(() => settled, { timeout: 5000 }).toBe(true)
      await page.unroute('**/api/club')
      await opener.click()
      await dialog.getByLabel('Choose player', { exact: true }).selectOption(String(target.id))
      await expect(player.getByLabel(/^Name/)).toHaveValue('QA Confirmed After Refresh')
      await expect(dialog.getByRole('button', { name: 'Save player details', exact: true })).toBeEnabled()
      expect(updates).toBe(1)
      expect(await owned.rows('roster_entries', { id: `eq.${sibling.id}` })).toEqual([sibling])
      expect(await owned.rows('bookings', { id: `eq.${booking.id}` })).toEqual(bookingBefore)
      expect(await owned.rows('checkouts', { id: `eq.${checkout.id}` })).toEqual(checkoutBefore)
    } finally {
      release()
      if (updates) await expect.poll(() => settled, { timeout: 5000 }).toBe(true)
      await page.unroute('**/api/club')
    }
  })
